import SwiftUI

/// A simple frequency summary of logged side effects — the "pattern report you
/// can show your prescriber" from the product's differentiation strategy. Not a
/// diagnostic tool; it just aggregates what the user already logged.
struct SideEffectSummaryCard: View {
    let logs: [SideEffectLog]

    private struct SymptomTally: Identifiable {
        let symptom: SideEffectSymptom
        let count: Int
        let averageSeverity: Double
        var id: SideEffectSymptom { symptom }
    }

    private var tallies: [SymptomTally] {
        Dictionary(grouping: logs, by: \.symptom)
            .map { symptom, entries in
                SymptomTally(
                    symptom: symptom,
                    count: entries.count,
                    averageSeverity: entries.reduce(0.0) { $0 + Double($1.severity) } / Double(entries.count)
                )
            }
            .sorted { $0.count > $1.count }
    }

    /// The card's copy has always said "bring this to your appointment," but there
    /// was no way to actually get the summary out of the app except a screenshot.
    /// This renders the same tallies as plain text so `ShareLink` can hand it to
    /// Messages, Mail, or Notes — something a prescriber can actually read as text.
    private var dateRangeText: String? {
        let dates = logs.map(\.date)
        guard let earliest = dates.min(), let latest = dates.max() else { return nil }
        if Calendar.current.isDate(earliest, inSameDayAs: latest) {
            return earliest.formatted(.dateTime.month(.abbreviated).day().year())
        }
        return "\(earliest.formatted(.dateTime.month(.abbreviated).day())) – \(latest.formatted(.dateTime.month(.abbreviated).day().year()))"
    }

    private var shareText: String {
        var lines = ["Side-effect summary" + (dateRangeText.map { " (\($0))" } ?? "")]
        lines.append("")
        if tallies.isEmpty {
            lines.append("No side effects logged in this period.")
        } else {
            for tally in tallies {
                let severity = String(format: "%.1f", tally.averageSeverity)
                lines.append("\(tally.symptom.displayName): \(tally.count)x, avg severity \(severity)/5")
            }
        }
        lines.append("")
        lines.append("Generated by Sustain. Not a diagnosis, for discussion with your prescriber.")
        return lines.joined(separator: "\n")
    }

    /// Recomputed on demand (not cached in `@State`) — matches `shareText`'s own
    /// existing pattern, and generating a few table rows of text into a PDF is
    /// fast enough that caching it would be the kind of complexity this app's
    /// realistic data scale doesn't justify (the same "know when to say no"
    /// discipline applied throughout the performance pass elsewhere in this
    /// codebase). `nil` only if the temporary directory somehow isn't writable —
    /// the PDF share option simply doesn't render in that case rather than
    /// presenting a broken share sheet.
    private var pdfFileURL: URL? {
        SideEffectReportPDFGenerator.generateTemporaryFile(
            rows: tallies.map {
                SideEffectReportPDFGenerator.SymptomRow(displayName: $0.symptom.displayName, count: $0.count, averageSeverity: $0.averageSeverity)
            },
            dateRangeText: dateRangeText,
            disclaimer: MedicalSources.disclaimer
        )
    }

    var body: some View {
        VStack(alignment: .leading, spacing: 12) {
            HStack {
                Text("Side-effect patterns")
                    .font(.headline)
                Spacer()
                // A real, downloadable PDF (the specific artifact two competitor
                // teardowns praised — comp-015, comp-024 in
                // Documentation/sustain-pros-and-cons.json) alongside the
                // original plain-text share, not instead of it: text is still
                // the faster path for pasting into Messages or a portal's
                // free-text field.
                if !tallies.isEmpty {
                    Menu {
                        if let pdfFileURL {
                            ShareLink("Share as PDF", item: pdfFileURL)
                        }
                        ShareLink("Share as text", item: shareText)
                    } label: {
                        Image(systemName: "square.and.arrow.up")
                            .font(.subheadline)
                            .foregroundStyle(Theme.primary)
                    }
                    .accessibilityLabel("Share side-effect summary")
                }
            }

            if tallies.isEmpty {
                Text("No side effects logged in this period")
                    .font(.caption)
                    .foregroundStyle(.secondary)
            } else {
                ForEach(tallies.prefix(5)) { tally in
                    HStack {
                        Image(systemName: tally.symptom.systemImage)
                            .foregroundStyle(Theme.warning)
                            .frame(width: 22)
                        Text(tally.symptom.displayName)
                            .font(.subheadline)
                        Spacer()
                        Text("\(tally.count)×")
                            .font(.subheadline.weight(.semibold))
                            .foregroundStyle(.secondary)
                        severityDots(tally.averageSeverity)
                    }
                    // The severity dots below are purely visual (fill vs. empty
                    // circles) with no text equivalent — never audited before this
                    // pass, and a real one-way information loss for VoiceOver: a
                    // sighted user can see severity at a glance, a VoiceOver user
                    // previously got nothing for it at all, only the count. This
                    // combines the row into one element with an explicit severity
                    // value instead of announcing five unlabeled circles.
                    .accessibilityElement(children: .combine)
                    .accessibilityLabel("\(tally.symptom.displayName), logged \(tally.count) times")
                    .accessibilityValue("Average severity \(String(format: "%.1f", tally.averageSeverity)) of 5")
                }

                Text("Not a diagnosis. Tap the share icon above to send this to your prescriber.")
                    .font(.caption2)
                    .foregroundStyle(.secondary)
                    .padding(.top, 4)
            }
        }
        .cardStyle()
    }

    private func severityDots(_ average: Double) -> some View {
        HStack(spacing: 2) {
            ForEach(1...5, id: \.self) { level in
                Circle()
                    .fill(Double(level) <= average.rounded() ? Theme.warning : Theme.warning.opacity(0.2))
                    .frame(width: 5, height: 5)
            }
        }
    }
}

#Preview {
    SideEffectSummaryCard(logs: [
        SideEffectLog(symptom: .nausea, severity: 3),
        SideEffectLog(symptom: .nausea, severity: 2),
        SideEffectLog(symptom: .fatigue, severity: 4),
    ])
    .padding()
}
